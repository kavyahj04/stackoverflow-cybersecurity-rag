"""The web API. It adds no RAG logic: each route calls the pipeline and returns JSON.

    POST /api/ask      question -> cited answer (search + LLM)
    POST /api/search   query -> matching threads (search only: fast, no LLM cost)
    GET  /api/health   is the database reachable (for uptime checks)
    GET  /api/info     dataset size and models (shown in the page footer)
    GET  /docs         interactive API docs, generated by FastAPI
    /                  the React frontend (frontend/dist), when it has been built

Run (from rag-dev):  .venv/bin/uvicorn rag.api.app:app --port 8000

What the API adds around the pipeline:
- Startup: the connection pool, the OpenAI client and the BM25 index (~8 s) are
  made once and shared by every request.
- A database connection is borrowed per request and given back before the LLM
  call, so a few slow answers can't use up the pool.
- A per-IP limit on paid requests, clear errors (out of credits, timeout,
  database down) and one log line per request with timings and token counts.
"""
import logging
import time
import uuid
from collections import defaultdict, deque
from contextlib import asynccontextmanager, contextmanager
from threading import Lock

import openai
import psycopg
from fastapi import FastAPI, HTTPException, Request
from fastapi.exceptions import RequestValidationError
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse
from fastapi.staticfiles import StaticFiles
from openai import OpenAI

from rag.api.schemas import (AnswerOut, AskRequest, InfoOut, SearchOut, SearchRequest, answer_out,
                             thread_out)
from rag.config import ROOT_DIR, get_settings
from rag.db import make_pool
from rag.generation.answer import RagPipeline
from rag.retrieval.bm25 import BM25
from rag.retrieval.dense import DenseRetriever
from rag.retrieval.hybrid import HybridRetriever
from rag.retrieval.store import ThreadStore

FRONTEND_DIR = ROOT_DIR / "frontend" / "dist"
log = logging.getLogger("rag.api")


class Services:
    """The long-lived objects every request shares."""

    def __init__(self):
        settings = get_settings()
        self.pool = make_pool()
        self.openai = OpenAI(timeout=settings.llm_timeout_s, max_retries=2)  # safe to share between threads
        with self.pool.connection() as conn:
            self.bm25 = BM25.from_database(conn)  # read-only after this, so it is shared too
        self.threads = len(self.bm25.question_ids)

    @contextmanager
    def pipeline(self):
        """A pipeline on a borrowed connection. The connection goes back to the pool at the end of the with."""
        with self.pool.connection() as conn:
            retriever = HybridRetriever(DenseRetriever(conn, self.openai), self.bm25)
            yield RagPipeline(retriever, ThreadStore(conn), client=self.openai)

    def ping(self) -> bool:
        try:
            with self.pool.connection() as conn:
                conn.execute("SELECT 1")
            return True
        except psycopg.Error:
            return False

    def close(self):
        self.pool.close()


class RateLimiter:
    """At most `per_minute` requests per key in any 60 seconds (a sliding window)."""

    def __init__(self, per_minute: int):
        self.per_minute = per_minute
        self.times: dict[str, deque] = defaultdict(deque)
        self.lock = Lock()  # requests run in several threads at once

    def allow(self, key: str) -> bool:
        now = time.monotonic()
        with self.lock:
            times = self.times[key]
            while times and now - times[0] >= 60:
                times.popleft()
            if len(times) >= self.per_minute:
                return False
            times.append(now)
            return True


class DailyCap:
    """At most `per_day` requests from everyone together per UTC day."""

    def __init__(self, per_day: int):
        self.per_day = per_day
        self.day = None
        self.count = 0
        self.lock = Lock()

    def allow(self) -> bool:
        today = time.strftime("%Y-%m-%d", time.gmtime())
        with self.lock:
            if today != self.day:
                self.day, self.count = today, 0
            if self.count >= self.per_day:
                return False
            self.count += 1
            return True


def _client_ip(request: Request) -> str:
    header = get_settings().client_ip_header
    if header and request.headers.get(header):
        return request.headers[header].split(",")[0].strip()
    return request.client.host if request.client else "unknown"


def _limit(limiter: RateLimiter, request: Request):
    if not limiter.allow(_client_ip(request)):
        raise HTTPException(429, f"Too many requests: the limit is {limiter.per_minute} per minute. "
                                 "Please wait a moment and try again.")


def create_app(make_services=Services) -> FastAPI:
    """make_services is swapped for fakes in the tests (no database, no OpenAI)."""
    settings = get_settings()

    @asynccontextmanager
    async def lifespan(app: FastAPI):
        start = time.time()
        app.state.services = make_services()
        log.info("ready in %.1fs: %d threads searchable", time.time() - start, app.state.services.threads)
        yield
        app.state.services.close()

    app = FastAPI(title="Security Q&A Research API", version="1.0",
                  description="Cited answers from Security Stack Exchange discussions.", lifespan=lifespan)
    ask_limiter = RateLimiter(settings.ask_per_minute)
    search_limiter = RateLimiter(settings.ask_per_minute * 3)
    daily_cap = DailyCap(settings.ask_per_day)

    # The frontend on Vercel is a different address; browsers only let it call us if we list it
    if settings.cors_origins:
        app.add_middleware(CORSMiddleware, allow_origins=list(settings.cors_origins),
                           allow_methods=["GET", "POST"], allow_headers=["Content-Type"],
                           expose_headers=["X-Request-ID"], max_age=600)

    # --- one log line and a request id per request -------------------------------------------------

    @app.middleware("http")
    async def request_log(request: Request, call_next):
        request.state.id = uuid.uuid4().hex[:12]
        start = time.time()
        response = await call_next(request)
        response.headers["X-Request-ID"] = request.state.id
        if request.url.path.startswith("/api/"):
            log.info("%s %s %s %d %.0fms", request.state.id, request.method, request.url.path,
                     response.status_code, (time.time() - start) * 1000)
        return response

    # --- errors a researcher can understand; details stay in our log ------------------------------

    def error(request: Request, status: int, message: str, exc: Exception) -> JSONResponse:
        rid = getattr(request.state, "id", "-")
        log.error("%s %s: %s", rid, type(exc).__name__, exc)
        return JSONResponse({"detail": message, "request_id": rid}, status_code=status)

    @app.exception_handler(RequestValidationError)
    async def bad_input(request: Request, exc: RequestValidationError):
        # One readable sentence instead of pydantic's list of errors
        first = exc.errors()[0]
        message = str(first.get("msg", "Invalid request.")).removeprefix("Value error, ")
        return JSONResponse({"detail": message}, status_code=422)

    @app.exception_handler(openai.RateLimitError)
    async def openai_limit(request: Request, exc: openai.RateLimitError):
        # OpenAI sends code "credit_balance_exhausted" with type "insufficient_quota" (older: code "insufficient_quota")
        if {exc.code, getattr(exc, "type", None)} & {"insufficient_quota", "credit_balance_exhausted"}:
            return error(request, 503, "The service's OpenAI account has no credits left. "
                                       "Please tell the administrator.", exc)
        return error(request, 503, "The language model is busy. Please try again in a minute.", exc)

    @app.exception_handler(openai.APITimeoutError)
    async def openai_timeout(request: Request, exc: Exception):
        return error(request, 504, "The language model took too long to answer. Please try again.", exc)

    @app.exception_handler(openai.APIError)
    async def openai_error(request: Request, exc: Exception):
        return error(request, 502, "The language model service returned an error. Please try again.", exc)

    @app.exception_handler(psycopg.Error)   # includes the pool timing out (all connections busy)
    async def database_error(request: Request, exc: Exception):
        return error(request, 503, "The database is unavailable or busy. Please try again shortly.", exc)

    @app.exception_handler(Exception)
    async def unexpected(request: Request, exc: Exception):
        log.exception("unexpected error")
        return error(request, 500, "Something went wrong on our side.", exc)

    # --- routes. Plain `def`: FastAPI runs them in worker threads, since our code is not async ----

    @app.post("/api/ask", response_model=AnswerOut)
    def ask(body: AskRequest, request: Request):
        _limit(ask_limiter, request)
        if not daily_cap.allow():
            raise HTTPException(429, "The service has reached its answer limit for today. "
                                     "Search still works; answers are available again tomorrow (UTC).")
        start = time.time()
        with request.app.state.services.pipeline() as pipeline:
            retrieval, blocks = pipeline.prepare(body.question)   # embedding + database
        answer = pipeline.answer(body.question, retrieval, blocks)  # LLM, connection already returned
        answer.usage["seconds"] = round(time.time() - start, 2)
        u = answer.usage
        log.info("%s ask found=%s exact=%s best=%s threads=%d tokens=%s/%s invalid=%s %.2fs",
                 request.state.id, answer.found, retrieval["exact_match"], retrieval["best_distance"],
                 len(blocks), u.get("prompt_tokens", 0), u.get("completion_tokens", 0),
                 answer.citations.invalid, u["seconds"])
        return answer_out(answer)

    @app.post("/api/search", response_model=SearchOut)
    def search(body: SearchRequest, request: Request):
        _limit(search_limiter, request)
        with request.app.state.services.pipeline() as pipeline:
            hits = pipeline.retriever.search(body.query)
            threads = pipeline.store.get_threads([h.question_id for h in hits])
        return SearchOut(query=body.query,
                         threads=[thread_out(h, threads[h.question_id]) for h in hits if h.question_id in threads])

    @app.get("/api/health")
    def health(request: Request):
        if request.app.state.services.ping():
            return {"status": "ok"}
        return JSONResponse({"status": "database unavailable"}, status_code=503)

    @app.get("/api/info", response_model=InfoOut)
    def info(request: Request):
        return InfoOut(threads=request.app.state.services.threads, llm_model=settings.llm_model,
                       embedding_model=settings.embedding_model,
                       context=f"top {settings.context_threads} threads x best {settings.max_answers_per_thread} answers",
                       max_question_chars=settings.max_question_chars)

    # The built frontend, served by the same server: one address, no cross-origin setup
    if FRONTEND_DIR.is_dir():
        app.mount("/", StaticFiles(directory=FRONTEND_DIR, html=True), name="frontend")

    return app


logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
app = create_app()
